using System.Globalization;
using QuickCover.Contracts;
using QuestPDF.Fluent;
using QuestPDF.Helpers;
using QuestPDF.Infrastructure;

namespace QuickCover.DocsWorker;

/// <summary>Renders the policy schedule: the one-page summary a customer keeps as proof of cover.</summary>
public sealed class PolicyDocumentRenderer(TimeProvider time)
{
    private static readonly CultureInfo UkCulture = CultureInfo.GetCultureInfo("en-GB");
    private const string Accent = "#0F6E56";

    public byte[] Render(PolicyIssued policy)
    {
        var generatedUtc = time.GetUtcNow().UtcDateTime;

        return Document.Create(doc => doc.Page(page =>
        {
            page.Size(PageSizes.A4);
            page.Margin(2, Unit.Centimetre);
            page.DefaultTextStyle(t => t.FontSize(11));

            page.Header().Row(row =>
            {
                row.RelativeItem().Text(t =>
                {
                    t.Span("Quick").FontSize(22).SemiBold();
                    t.Span("Cover").FontSize(22).SemiBold().FontColor(Accent);
                });
                row.RelativeItem().AlignRight().AlignBottom().Text("Policy schedule").FontSize(14).FontColor(Colors.Grey.Darken1);
            });

            page.Content().PaddingVertical(1, Unit.Centimetre).Column(col =>
            {
                col.Spacing(14);

                col.Item().Text("Taxi insurance").FontSize(18).SemiBold();

                col.Item().Table(table =>
                {
                    table.ColumnsDefinition(c =>
                    {
                        c.ConstantColumn(5, Unit.Centimetre);
                        c.RelativeColumn();
                    });

                    void Row(string label, string value)
                    {
                        table.Cell().BorderBottom(0.5f).BorderColor(Colors.Grey.Lighten2).PaddingVertical(6)
                            .Text(label).FontColor(Colors.Grey.Darken1);
                        table.Cell().BorderBottom(0.5f).BorderColor(Colors.Grey.Lighten2).PaddingVertical(6)
                            .Text(value).SemiBold();
                    }

                    Row("Policy number", policy.PolicyNumber);
                    Row("Customer reference", policy.CustomerId);
                    Row("Period of cover", $"{FormatDate(policy.StartDate)} to {FormatDate(policy.EndDate)} (both days inclusive)");
                    Row("Annual premium", policy.AnnualPremium.ToString("C", UkCulture));
                    Row("Issued", policy.IssuedUtc.ToString("d MMMM yyyy, HH:mm 'UTC'", UkCulture));
                    Row("Quote reference", policy.QuoteId.ToString()[..8].ToUpperInvariant());
                });

                col.Item().PaddingTop(10).Background(Colors.Grey.Lighten4).Padding(12).Text(
                    "This is a practice document generated by the QuickCover demo system. " +
                    "It is not a real insurance policy and provides no cover.")
                    .FontSize(9).FontColor(Colors.Grey.Darken2);
            });

            page.Footer().Row(row =>
            {
                row.RelativeItem().Text($"Generated {generatedUtc.ToString("yyyy-MM-dd HH:mm 'UTC'", UkCulture)}")
                    .FontSize(8).FontColor(Colors.Grey.Medium);
                row.RelativeItem().AlignRight().Text(t =>
                {
                    t.DefaultTextStyle(s => s.FontSize(8).FontColor(Colors.Grey.Medium));
                    t.Span("Page ");
                    t.CurrentPageNumber();
                    t.Span(" of ");
                    t.TotalPages();
                });
            });
        })).GeneratePdf();
    }

    private static string FormatDate(DateOnly date) => date.ToString("d MMMM yyyy", UkCulture);
}
